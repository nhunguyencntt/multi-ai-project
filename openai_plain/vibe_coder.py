import os
import json
import requests
import openai

def load_task_spec():
    if os.path.exists("task_spec.json"):
        with open("task_spec.json", "r", encoding="utf-8") as f:
            return f.read()
    return "Tạo ứng dụng theo yêu cầu mặc định."

def call_chatgpt(prompt):
    print("🤖 [1/4] Đang thử nghiệm sinh code với ChatGPT...")
    client = openai.OpenAI(api_key=os.environ.get("OPENAI_API_KEY"))
    response = client.chat.completions.create(
        model="gpt-4o",
        messages=[{"role": "user", "content": prompt}]
    )
    return response.choices[0].message.content

def call_grok(prompt):
    print("🤖 [2/4] ChatGPT không khả dụng/hết token. Chuyển sang Grok (xAI)...")
    url = "https://api.x.ai/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {os.environ.get('GROK_API_KEY')}",
        "Content-Type": "application/json"
    }
    data = {
        "model": "grok-beta",
        "messages": [{"role": "user", "content": prompt}]
    }
    response = requests.post(url, headers=headers, json=data)
    response.raise_for_status()
    return response.json()['choices'][0]['message']['content']

def call_deepseek(prompt):
    print("🤖 [3/4] Grok không khả dụng/hết token. Chuyển sang DeepSeek...")
    deepseek_key = os.environ.get("DEEPSEEK_API_KEY")
    if not deepseek_key:
        raise Exception("DEEPSEEK_API_KEY chưa được cấu hình!")

    client = openai.OpenAI(
        api_key=deepseek_key,
        base_url="https://api.deepseek.com"
    )
    response = client.chat.completions.create(
        model="deepseek-coder",
        messages=[{"role": "user", "content": prompt}]
    )
    return response.choices[0].message.content

def call_manus(prompt):
    print("🤖 [4/4] DeepSeek không khả dụng. Chuyển sang Manus...")
    manus_key = os.environ.get("MANUS_API_KEY")
    if not manus_key:
        raise Exception("Manus API Key chưa được cấu hình!")
    return "// Generated by Manus\nprint('Code generated by Manus')"

def generate_code_with_fallback(task_spec):
    prompt = f"Dựa vào spec sau, hãy viết source code hoàn chỉnh cho ứng dụng:\n{task_spec}"
    
    engines = [call_chatgpt, call_grok, call_deepseek, call_manus]
    
    for engine in engines:
        try:
            generated_code = engine(prompt)
            print("✅ Sinh source code thành công!")
            return generated_code
        except Exception as e:
            print(f"⚠️ Lỗi ở LLM hiện tại: {e}")
            continue
            
    raise Exception("❌ Tất cả các AI Model (ChatGPT, Grok, DeepSeek, Manus) đều hết token hoặc gặp lỗi!")

if __name__ == "__main__":
    spec = load_task_spec()
    code = generate_code_with_fallback(spec)
    
    os.makedirs("generated_app", exist_ok=True)
    with open("generated_app/app_output.md", "w", encoding="utf-8") as f:
        f.write(code)
