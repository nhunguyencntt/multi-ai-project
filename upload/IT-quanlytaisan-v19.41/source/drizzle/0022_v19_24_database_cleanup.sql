-- IT-quanlytaisan v19.24
-- Final cleanup of legacy data introduced by early v5-v19 upgrades.
-- The application now uses only explicit, category-scoped technical specifications.
-- Bản quyền & Dịch vụ and Hạ tầng & Mạng are independent modules, not asset categories.

SET @db := DATABASE();
CREATE TABLE IF NOT EXISTS itq_schema_versions (
  version varchar(40) PRIMARY KEY,
  appliedAt timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------------
-- 1. Remove Bản quyền & Dịch vụ from assetCategories.
-- License records remain in licenses; mirrored LIC-* asset/inventory rows remain
-- for operational compatibility but are detached from the asset catalog.
-- ---------------------------------------------------------------------------
UPDATE assets a
JOIN assetCategories c ON c.id = a.categoryId
SET a.categoryId = NULL
WHERE LOWER(TRIM(c.name)) = 'bản quyền & dịch vụ'
   OR a.assetCode LIKE 'LIC-%';

UPDATE inventoryItems i
JOIN assetCategories c ON c.id = i.categoryId
SET i.categoryId = NULL
WHERE LOWER(TRIM(c.name)) = 'bản quyền & dịch vụ'
   OR i.itemCode LIKE 'LIC-%';

DELETE v
FROM assetSpecificationValues v
JOIN assetSpecificationFields f ON f.id = v.fieldId
JOIN assetCategories c ON c.id = f.categoryId
WHERE LOWER(TRIM(c.name)) = 'bản quyền & dịch vụ';

DELETE l
FROM assetSpecificationFieldCategories l
JOIN assetCategories c ON c.id = l.categoryId
WHERE LOWER(TRIM(c.name)) = 'bản quyền & dịch vụ';

DELETE f
FROM assetSpecificationFields f
JOIN assetCategories c ON c.id = f.categoryId
WHERE LOWER(TRIM(c.name)) = 'bản quyền & dịch vụ';

DELETE FROM assetCategories
WHERE LOWER(TRIM(name)) IN ('bản quyền & dịch vụ', 'hạ tầng & mạng');

-- ---------------------------------------------------------------------------
-- 2. Remove every old global/common technical field and the legacy
-- manufacturer/model/brand fields generated by old specification templates.
-- No technical field is allowed to exist without a concrete asset category.
-- ---------------------------------------------------------------------------
DELETE v
FROM assetSpecificationValues v
JOIN assetSpecificationFields f ON f.id = v.fieldId
WHERE f.categoryId IS NULL
   OR LOWER(f.code) REGEXP '^(manufacturer|model|brand)(_|$)';

DELETE l
FROM assetSpecificationFieldCategories l
LEFT JOIN assetSpecificationFields f ON f.id = l.fieldId
LEFT JOIN assetCategories c ON c.id = l.categoryId
WHERE f.id IS NULL
   OR f.categoryId IS NULL
   OR c.id IS NULL
   OR LOWER(TRIM(c.name)) IN ('bản quyền & dịch vụ', 'hạ tầng & mạng');

DELETE FROM assetSpecificationFields
WHERE categoryId IS NULL
   OR LOWER(code) REGEXP '^(manufacturer|model|brand)(_|$)';

-- Remove values whose field does not belong to the asset's current category.
-- This prevents old cross-category values from resurfacing in asset forms.
DELETE v
FROM assetSpecificationValues v
JOIN assets a ON a.id = v.assetId
JOIN assetSpecificationFields f ON f.id = v.fieldId
LEFT JOIN assetSpecificationFieldCategories l
  ON l.fieldId = f.id AND l.categoryId = a.categoryId
WHERE a.categoryId IS NULL
   OR NOT (f.categoryId = a.categoryId OR l.fieldId IS NOT NULL);

-- Remove orphan specification values/links left by historical upgrades.
DELETE v
FROM assetSpecificationValues v
LEFT JOIN assetSpecificationFields f ON f.id = v.fieldId
LEFT JOIN assets a ON a.id = v.assetId
WHERE f.id IS NULL OR a.id IS NULL;

DELETE l
FROM assetSpecificationFieldCategories l
LEFT JOIN assetSpecificationFields f ON f.id = l.fieldId
LEFT JOIN assetCategories c ON c.id = l.categoryId
WHERE f.id IS NULL OR c.id IS NULL;

-- ---------------------------------------------------------------------------
-- 3. Normalize department aliases created by the old imported register.
-- References are moved to the canonical short-code department before the
-- obsolete duplicate name is removed. No live asset/user/ticket is deleted.
-- ---------------------------------------------------------------------------
DROP TEMPORARY TABLE IF EXISTS itq_department_aliases;
CREATE TEMPORARY TABLE itq_department_aliases (
  legacy_name varchar(160) NOT NULL,
  canonical_code varchar(40) NOT NULL
);
INSERT INTO itq_department_aliases VALUES
  ('Ban Cà Mau','BCM'),
  ('Ban Cần Thơ','BCT'),
  ('Ban Quảng Trị','BQT'),
  ('Ban Đông Anh','BĐA'),
  ('Ban Đội Cấn','BĐC'),
  ('P.KD','KD'),
  ('P.QLTK','QLTK'),
  ('P.TCHC&KH','TCHC&KH'),
  ('P.TCKT','TCKT');

-- Ensure the canonical department exists before references are moved.
INSERT IGNORE INTO departments (code,name,active) VALUES
  ('BCM','BCM',1),('BCT','BCT',1),('BQT','BQT',1),('BĐA','BĐA',1),
  ('BĐC','BĐC',1),('KD','KD',1),('QLTK','QLTK',1),('TCHC&KH','TCHC&KH',1),('TCKT','TCKT',1);

-- Only merge an alias after the canonical target exists.
UPDATE assets a
JOIN departments oldd ON oldd.id = a.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET a.departmentId = newd.id;

UPDATE assetUsers u
JOIN departments oldd ON oldd.id = u.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET u.departmentId = newd.id;

UPDATE tickets t
JOIN departments oldd ON oldd.id = t.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET t.departmentId = newd.id;

UPDATE assetAllocations a
JOIN departments oldd ON oldd.id = a.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET a.departmentId = newd.id;

UPDATE inventoryChecks i
JOIN departments oldd ON oldd.id = i.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET i.departmentId = newd.id;

UPDATE reportTemplates r
JOIN departments oldd ON oldd.id = r.departmentId
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
SET r.departmentId = newd.id;

DELETE oldd
FROM departments oldd
JOIN itq_department_aliases m ON m.legacy_name = oldd.name
JOIN departments newd ON newd.code = m.canonical_code
WHERE oldd.id <> newd.id;

DROP TEMPORARY TABLE itq_department_aliases;

INSERT IGNORE INTO itq_schema_versions(version) VALUES ('v19.24');
